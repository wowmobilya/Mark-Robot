"""Build the pinned, hash-verified browser voice inventory (no weight download).

Run after the official WebGPU build and native reference embedding extraction.
The generated pack contains URLs for model shards, never the shards themselves.
"""
import argparse
import ast
import hashlib
import json
import math
from pathlib import Path
import shutil
import struct
import urllib.request

ROOT = Path(__file__).resolve().parents[1]
REVISION = '2921b8821772b0bd10a04456863d21abf9d2f283'
RUNTIME_REVISION = 'a50e14117d99181ba7f28047b451ba03ba1a09a9'
HUB = f'https://huggingface.co/Zyphra/ZONOS3-Mini/resolve/{REVISION}/'
VENDOR = ROOT / 'vendor/zonos3/a50e141'
MODEL = VENDOR / 'model'


def read_url(url):
    with urllib.request.urlopen(url, timeout=45) as response:
        return response.read()


def sha(data):
    return hashlib.sha256(data).hexdigest()


def validate_embedding(data):
    if data[:8] != b'\x93NUMPY\x01\x00':
        raise ValueError('Expected a NumPy 1.0 embedding')
    count = struct.unpack('<H', data[8:10])[0]
    header = ast.literal_eval(data[10:10 + count].decode('ascii').strip())
    if header['descr'] != '<f4' or header['shape'] != (192,) or header['fortran_order']:
        raise ValueError('Expected little-endian float32[192]')
    values = struct.unpack('<192f', data[10 + count:])
    if not all(math.isfinite(value) for value in values) or not any(values):
        raise ValueError('Invalid speaker embedding')


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--embedding-dir', type=Path)
    parser.add_argument('--refresh-local', action='store_true')
    args = parser.parse_args()
    output = ROOT / 'reference-voice-assets.js'
    if args.refresh_local:
        current = json.loads(output.read_text().split('globalThis.WFReferenceVoiceAssets = ', 1)[1].rstrip().removesuffix(';'))
        # App adapters travel with the shell. Updating playback must not invalidate
        # an already installed 922 MB model pack.
        current['assets'] = [item for item in current['assets']
                             if item['id'] not in ('reference-voice-js', 'reference-voice-host-js')]
        for item in current['assets']:
            if item['url'].startswith('./'):
                data = (ROOT / item['url'][2:].split('?', 1)[0]).read_bytes()
                if item['id'].startswith('reference-') and item['url'].endswith('.npy'):
                    validate_embedding(data)
                item['bytes'] = len(data)
                item['sha256'] = sha(data)
        current['bytes'] = sum(item['bytes'] for item in current['assets'])
        output.write_text('/* Pinned public model assets; generated by tools/prepare-reference-voice.py. */\nglobalThis.WFReferenceVoiceAssets = ' + json.dumps(current, ensure_ascii=False, indent=2) + ';\n')
        print(json.dumps({'files': len(current['assets']), 'bytes': current['bytes']}))
        return
    if args.embedding_dir is None:
        parser.error('--embedding-dir is required for the initial inventory')
    api = f'https://huggingface.co/api/models/Zyphra/ZONOS3-Mini/tree/{REVISION}/web?recursive=true'
    rows = {row['path']: row for row in json.loads(read_url(api)) if row['type'] == 'file'}
    assets = []

    def local(path, ident, kind='application/octet-stream', model_path=None, query=''):
        data = path.read_bytes()
        asset = {'id': ident, 'url': './' + path.relative_to(ROOT).as_posix() + query,
                 'bytes': len(data), 'sha256': sha(data), 'type': kind}
        if model_path is not None:
            asset['modelPath'] = model_path
        assets.append(asset)

    def model_file(rel):
        upstream = 'web/' + rel
        row = rows[upstream]
        if rel.endswith('.bin'):
            expected = row.get('lfs', {}).get('oid')
            if not expected or len(expected) != 64:
                raise ValueError('Missing published shard SHA256: ' + rel)
            assets.append({'id': rel.replace('/', '-').replace('.', '-'),
                           'url': HUB + upstream, 'bytes': row['size'],
                           'sha256': expected, 'type': 'application/octet-stream', 'modelPath': rel})
        else:
            data = read_url(HUB + upstream)
            if len(data) != row['size'] or (row.get('lfs') and sha(data) != row['lfs']['oid']):
                raise ValueError('Source integrity mismatch: ' + rel)
            target = MODEL / rel
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_bytes(data)
            local(target, rel.replace('/', '-').replace('.', '-'),
                  'application/json' if rel.endswith('.json') else 'application/octet-stream', rel)

    largest = 0
    for part in ['backbone', 'zac']:
        model_file(part + '/manifest.json')
        info = json.loads((MODEL / part / 'manifest.json').read_bytes())
        largest = max(largest, *(item['nbytes'] for item in info['tensors'].values()))
        for shard in info['shards']:
            model_file(part + '/' + shard)

    model_file('companions/steer.gguf')
    index = json.loads(read_url(HUB + 'web/laci/index.json'))
    selected = {key: index[key] for key in ['ar', 'tr', 'en_us', 'en_gb', 'fr_fr', 'ru']}
    for name in sorted(set(selected.values())):
        model_file('laci/' + name)
    index_path = MODEL / 'laci/index.json'
    index_path.write_text(json.dumps(selected, indent=2) + '\n')
    local(index_path, 'laci-index', 'application/json', 'laci/index.json')
    voices_path = MODEL / 'voices/voices.json'
    voices_path.parent.mkdir(parents=True, exist_ok=True)
    voices_path.write_text('[]\n')
    local(voices_path, 'voice-index', 'application/json', 'voices/voices.json')

    embeddings = {}
    source_metadata = json.loads((ROOT / 'assets/robot-identity/metadata.json').read_bytes())
    provenance = json.loads((args.embedding_dir / 'embedding-manifest.json').read_bytes())
    for language in ['ar', 'ar-EG', 'tr', 'en', 'fr', 'ru']:
        target = ROOT / 'assets/reference-voice/embeddings' / (language + '.npy')
        target.parent.mkdir(parents=True, exist_ok=True)
        data = (args.embedding_dir / f'mark-{language}.embedding.npy').read_bytes()
        validate_embedding(data)
        target.write_bytes(data)
        local(target, 'reference-' + language)
        embeddings[language] = './' + target.relative_to(ROOT).as_posix()
        original = (ROOT / source_metadata['voices'][language]['path']).read_bytes()
        if sha(original) != source_metadata['voices'][language]['sha256']:
            raise ValueError('Greeting reference changed: ' + language)
    (ROOT / 'assets/reference-voice/embeddings/provenance.json').write_text(json.dumps(provenance, ensure_ascii=False, indent=2) + '\n')

    for filename in ['engine.js', 'worker.js', 'upstream-worker.js', 'codec-worker.js']:
        local(VENDOR / filename, 'runtime-' + filename.replace('.', '-'), 'text/javascript')

    result = {'version': 1, 'id': 'mark-zonos3-reference-v1', 'cacheName': 'infinity-offline-voice-v1',
              'engineBase': './vendor/zonos3/a50e141/', 'runtimeRevision': RUNTIME_REVISION,
              'modelRevision': REVISION, 'minBufferBytes': max(largest, 128 * 1024 * 1024),
              'sourceURL': f'https://huggingface.co/Zyphra/ZONOS3-Mini/tree/{REVISION}',
              'licenseURL': './vendor/zonos3/a50e141/README.md', 'embeddings': embeddings,
              'bytes': sum(item['bytes'] for item in assets), 'assets': assets}
    output.write_text('/* Pinned public model assets; generated by tools/prepare-reference-voice.py. */\nglobalThis.WFReferenceVoiceAssets = ' + json.dumps(result, ensure_ascii=False, indent=2) + ';\n')
    print(json.dumps({'files': len(assets), 'bytes': result['bytes'], 'minBufferBytes': result['minBufferBytes'],
                      'embeddings': list(embeddings)}, ensure_ascii=False))


if __name__ == '__main__':
    main()
